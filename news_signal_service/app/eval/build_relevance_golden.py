def main() -> None:
    out = Path(__file__).resolve().parents[2] / "data" / "eval" / "relevance_golden.csv"
    rows = [(h, s, "real", 0) for h, s in REAL_POSITIVE]
    rows += [(h, "", "real", 0) for h, _ in REAL_NEGATIVE]
    rows += [(h, "", "real", 1) for h in HARD_NEGATIVE]
    rows += [(h, s, "authored", 0) for h, s in AUTHORED]
    with out.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["headline", "expected_seeds", "kind", "hard"])
        writer.writerows(rows)
    print(f"wrote {len(rows)} rows -> {out}")


if __name__ == "__main__":
    main()
